"""Generate HandsAssets.cpp from the UltimateXR hand assets in assets/vrhands.

The meshes are embedded as stored. The 1024x1024 albedo is box-filtered in linear light to a
512x512 sRGB base level plus a full mip chain, so the hands do not shimmer at arm's length.
"""
import argparse
import hashlib
import struct
import sys
from pathlib import Path

MESHES = [('BigHandLeft.uxrh', 'leftBytes', '6bb32e6f79ed6dba401bd36dd39d3178f8259096f889ef01c870d057134eb535'),
          ('BigHandRight.uxrh', 'rightBytes', '48b14a77efea68027f5ae6723994cadc06dac58708ecb7339cc16ecb1ade2478')]
ALBEDO_FILE = 'BigHandsAlbedo.rgba'
ALBEDO_SHA = '46ba8b2f08ce1ca420537e060f64be139dd39a22357d4ea5b9b7b69da2ba2ad4'
ALBEDO_SOURCE_SIZE = 1024
ALBEDO_SIZE = 512
CHAIN_SHA = '653e369285913f6fa3d535658c9c27284238dc58af604718ae146cca71454d7a'


def check_mesh(name, data):
    magic, version, nv, ni = struct.unpack('<4sIII', data[:16])
    if (magic != b'UXRH' or version != 1 or not nv or nv > 5000 or not ni or ni > 27000 or ni % 3
            or len(data) != 16 + 104 * nv + 2 * ni):
        raise ValueError('invalid UXRH mesh ' + name)


def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def linear_to_srgb(c):
    c = min(max(c, 0.0), 1.0)
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def albedo_chain(data):
    """Linear-light 2x2 box filter 1024 -> 512 -> ... -> 1, levels from ALBEDO_SIZE down."""
    if len(data) != ALBEDO_SOURCE_SIZE * ALBEDO_SOURCE_SIZE * 4:
        raise ValueError('unexpected hand albedo size')
    lut = [srgb_to_linear(i / 255.0) for i in range(256)]
    alut = [i / 255.0 for i in range(256)]
    size = ALBEDO_SOURCE_SIZE
    planes = [[(lut if c < 3 else alut)[b] for b in data[c::4]] for c in range(4)]
    chain = bytearray()
    while size > 1:
        half = size // 2
        nxt = []
        for plane in planes:
            out = [0.0] * (half * half)
            for y in range(half):
                r0 = plane[(2 * y) * size:(2 * y + 1) * size]
                r1 = plane[(2 * y + 1) * size:(2 * y + 2) * size]
                out[y * half:(y + 1) * half] = [(r0[2 * x] + r0[2 * x + 1] + r1[2 * x] + r1[2 * x + 1]) * 0.25
                                                for x in range(half)]
            nxt.append(out)
        planes, size = nxt, half
        if size <= ALBEDO_SIZE:
            level = bytearray(size * size * 4)
            for c in range(4):
                if c < 3:
                    level[c::4] = bytes(int(linear_to_srgb(v) * 255.0 + 0.5) for v in planes[c])
                else:
                    level[c::4] = bytes(int(min(max(v, 0.0), 1.0) * 255.0 + 0.5) for v in planes[c])
            chain += level
    return bytes(chain)


def byte_array(name, data):
    rows = [','.join(str(b) for b in data[i:i + 128]) for i in range(0, len(data), 128)]
    return f'alignas(16) const unsigned char {name}[{len(data)}] = {{\n' + ',\n'.join(rows) + '\n};\n'


def build_source(assets):
    lines = ['// Generated by tools/hands_assets.py from assets/vrhands (UltimateXR BigHands, MIT). Do not edit.',
             '#include "vr/HandsAssets.h"', 'namespace rdrvr::vr::hands::assets {', 'namespace {']
    for filename, name, sha in MESHES:
        data = (assets / filename).read_bytes()
        if hashlib.sha256(data).hexdigest() != sha:
            raise SystemExit('ERROR: unexpected hand asset ' + filename)
        check_mesh(filename, data)
        lines.append(byte_array(name, data))
    data = (assets / ALBEDO_FILE).read_bytes()
    if hashlib.sha256(data).hexdigest() != ALBEDO_SHA:
        raise SystemExit('ERROR: unexpected hand asset ' + ALBEDO_FILE)
    chain = albedo_chain(data)
    if hashlib.sha256(chain).hexdigest() != CHAIN_SHA:
        raise SystemExit('ERROR: the hand albedo mip chain does not match vr/HandsAssets.h')
    lines.append(byte_array('albedoBytes', chain))
    lines += ['}', 'std::span<const unsigned char> leftMesh() noexcept {return leftBytes;}',
              'std::span<const unsigned char> rightMesh() noexcept {return rightBytes;}',
              'std::span<const unsigned char> albedo() noexcept {return albedoBytes;}', '}']
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--assets', required=True, help='assets/vrhands directory')
    parser.add_argument('--out', required=True, help='generated source directory')
    args = parser.parse_args(argv)
    target = Path(args.out) / 'vr'
    target.mkdir(parents=True, exist_ok=True)
    text = build_source(Path(args.assets))
    (target / 'HandsAssets.cpp').write_bytes(text.encode('ascii'))
    print(f'Generated {target / "HandsAssets.cpp"}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
